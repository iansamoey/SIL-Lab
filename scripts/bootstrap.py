#!/usr/bin/env python3
"""Lab bootstrap.

  init  - generate .env with random secrets (if missing), render the Keycloak realm,
          create log directories.
  kong  - wait for Keycloak, fetch the realm's RSA public key, render kong/kong.yml.

No secrets are committed to the repo: everything sensitive is generated into .env
(gitignored) and injected at render time. Standard library only.
"""
import base64
import json
import os
import secrets
import string
import sys
import textwrap
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / ".env"


def load_env() -> dict:
    env = {}
    for line in ENV_FILE.read_text().splitlines():
        if line.strip() and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip()
    return env


def init() -> None:
    values = {
        "KC_ADMIN_PASSWORD": secrets.token_hex(16),
        "POSTGRES_PASSWORD": secrets.token_hex(24),
        "CLAIMS_DB_PASSWORD": secrets.token_hex(24),
        "PATIENT_DB_PASSWORD": secrets.token_hex(24),
        "HOSPITAL_CLIENT_SECRET": secrets.token_hex(24),
        "INSURER_CLIENT_SECRET": secrets.token_hex(24),
        "INTERNAL_TOOL_CLIENT_SECRET": secrets.token_hex(24),
        "DAST_SCANNER_CLIENT_SECRET": secrets.token_hex(24),
        # Fernet key = urlsafe base64 of 32 random bytes
        "PHI_ENC_KEY": base64.urlsafe_b64encode(os.urandom(32)).decode(),
        "PHI_HMAC_KEY": secrets.token_hex(32),
    }
    existing = load_env() if ENV_FILE.exists() else {}
    missing = {k: v for k, v in values.items() if k not in existing}
    if missing:
        header = "" if ENV_FILE.exists() else "# Generated by scripts/bootstrap.py. LAB ONLY. Never commit this file.\n"
        with ENV_FILE.open("a") as fh:
            fh.write(header + "".join(f"{k}={v}\n" for k, v in missing.items()))
        ENV_FILE.chmod(0o600)
        print(f"added to .env: {', '.join(missing)}")
    env = load_env()

    tmpl = (ROOT / "keycloak/realm-sil.json.tmpl").read_text()
    realm = string.Template(tmpl).substitute(
        HOSPITAL_CLIENT_SECRET=env["HOSPITAL_CLIENT_SECRET"],
        INSURER_CLIENT_SECRET=env["INSURER_CLIENT_SECRET"],
        INTERNAL_TOOL_CLIENT_SECRET=env["INTERNAL_TOOL_CLIENT_SECRET"],
        DAST_SCANNER_CLIENT_SECRET=env["DAST_SCANNER_CLIENT_SECRET"],
    )
    json.loads(realm)  # fail fast on a broken template
    (ROOT / "keycloak/realm-sil.json").write_text(realm)
    print("rendered keycloak/realm-sil.json")

    for d in ("logs/kong", "logs/waf", "logs/ai-guard"):
        p = ROOT / d
        p.mkdir(parents=True, exist_ok=True)
        p.chmod(0o777)  # containers run as non-root users with different uids


def fetch_public_key(kc_url: str, timeout: int = 240) -> str:
    url = f"{kc_url}/realms/sil"
    deadline = time.time() + timeout
    while True:
        try:
            with urllib.request.urlopen(url, timeout=5) as r:
                return json.load(r)["public_key"]
        except Exception as exc:  # Keycloak still starting
            if time.time() > deadline:
                sys.exit(f"Keycloak not ready at {url}: {exc}")
            print("waiting for Keycloak...")
            time.sleep(5)


def to_pem(b64_der: str) -> str:
    body = "\n".join(textwrap.wrap(b64_der, 64))
    return f"-----BEGIN PUBLIC KEY-----\n{body}\n-----END PUBLIC KEY-----"


def render_kong(b64_der: str) -> None:
    pem = textwrap.indent(to_pem(b64_der), " " * 10)
    tmpl = (ROOT / "kong/kong.yml.tmpl").read_text()
    (ROOT / "kong/kong.yml").write_text(tmpl.replace("{{RSA_PUBLIC_KEY}}", pem))
    print("rendered kong/kong.yml with Keycloak realm public key")


def kong() -> None:
    kc_url = os.environ.get("KC_URL", "http://localhost:8180")
    render_kong(fetch_public_key(kc_url))


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "init":
        init()
    elif cmd == "kong":
        kong()
    else:
        sys.exit("usage: bootstrap.py init|kong")
